void CampusGuide::showCampusMenu()
{
    int choice;

    do
    {
        cout << "\n=========================================\n";
        cout << "          ARYA COLLEGE CAMPUS GUIDE\n";
        cout << "=========================================\n";
        cout << "1. Library\n";
        cout << "2. Computer Labs\n";
        cout << "3. Cafeteria\n";
        cout << "4. Hostel\n";
        cout << "5. Auditorium\n";
        cout << "6. Administration Office\n";
        cout << "7. Back to Main Menu\n";

        cout << "\nEnter your choice : ";
        cin >> choice;

        switch(choice)
        {
            case 1:
                library();
                break;

            case 2:
                computerLabs();
                break;

            case 3:
                cafeteria();
                break;

            case 4:
                hostel();
                break;

            case 5:
                auditorium();
                break;

            case 6:
                administrationOffice();
                break;

            case 7:
                cout << "\nReturning to Main Menu...\n";
                break;

            default:
                cout << "\nInvalid Choice! Please try again.\n";
        }

    } while(choice != 7);
}